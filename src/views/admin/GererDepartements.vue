<script setup>
import { ref, onMounted } from 'vue' 
import { useRouter, RouterLink } from 'vue-router'
import { useDepartmentStore } from '@/stores/departmentStore'
import { 
  BarChart3, 
  Users, 
  Activity, 
  MessageSquare, 
  Clock,
  TrendingUp,
  FileText,
  ArrowLeft,
  Plus,
  Edit,
  Trash2,
  User,
  AlertTriangle
} from 'lucide-vue-next';

const router = useRouter()
const departmentStore = useDepartmentStore()
const isSidebarOpen = ref(false)

// Fonctions sidebar
const toggleSidebar = () => {
  isSidebarOpen.value = !isSidebarOpen.value
}

const closeSidebar = () => {
  if (window.innerWidth <= 1024) {
    isSidebarOpen.value = false
  }
}

const goBack = () => {
  window.history.back()
}

// Fonctions utilitaires
const getInitials = (user) => {
  if (!user?.first_name || !user?.last_name) return 'N/A'
  return `${user.first_name.charAt(0)}${user.last_name.charAt(0)}`.toUpperCase()
}

onMounted(async () => {
  await departmentStore.fetchDepartments();
});

const addDepartement = () => {
  router.push({ name: 'AddUserDepartment' })
}

const goDelet = async (id) => {
  if (confirm(`Voulez-vous vraiment supprimer ce service ? Cette action est irréversible.`)) {
    try {
      await departmentStore.deleteDepartment(id)
    } catch (error) {
      console.error('Erreur suppression:', error)
    }
  }
}
</script>

